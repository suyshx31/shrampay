// Compiles contracts/ShramPay.sol -> artifacts/ShramPay.json (abi + bytecode)
const fs = require("fs"), path = require("path"), solc = require("solc");
const src = fs.readFileSync(path.join(__dirname, "../contracts/ShramPay.sol"), "utf8");
const input = { language: "Solidity", sources: { "ShramPay.sol": { content: src } },
  settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "metadata"] } } } };
fs.mkdirSync(path.join(__dirname, "../artifacts"), { recursive: true });
fs.writeFileSync(path.join(__dirname, "../artifacts/standard-input.json"), JSON.stringify(input, null, 2));
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errs = (out.errors || []).filter(e => e.severity === "error");
(out.errors || []).forEach(e => console.log(e.formattedMessage));
if (errs.length) process.exit(1);
const c = out.contracts["ShramPay.sol"].ShramPay;
fs.writeFileSync(path.join(__dirname, "../artifacts/ShramPay.json"),
  JSON.stringify({ abi: c.abi, bytecode: "0x" + c.evm.bytecode.object }, null, 2));
fs.writeFileSync(path.join(__dirname, "../artifacts/metadata.json"), c.metadata);
console.log("Compiled OK -> artifacts/ShramPay.json (+ metadata.json for verification)");
fs.writeFileSync(path.join(__dirname, "../docs/artifact.js"),
  "// generated by scripts/compile.js — do not edit\nwindow.SHRAMPAY_ARTIFACT = " +
  JSON.stringify({ abi: c.abi, bytecode: "0x" + c.evm.bytecode.object }) + ";\n");
console.log("Wrote docs/artifact.js");
